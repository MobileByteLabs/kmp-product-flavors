package com.mobilebytelabs.kmpflavors.internal

import java.io.File

/**
 * Phase 6 — emits KmpFlavorsRuntime expect + 5 actuals.
 * Files land at build/generated/kmpflavors-runtime/{sourceSet}/{pkgPath}/KmpFlavorsRuntime{.ext}.kt
 * Each actual reads from its platform-native source — NEVER hardcoded at codegen time.
 */
internal object RuntimeApiGenerator {

    /**
     * Emits a SINGLE concrete `object KmpFlavorsRuntime` into `commonMain` — no
     * `expect`/`actual`. A commonMain `expect` cannot reach a module's per-variant
     * compilations (`compileDevKotlinDesktop` etc.): the plugin replays the platform
     * `actual` srcDirs into each variant compilation's defaultSourceSet, but KGP's
     * source-set rules block the `expect` from following, leaving orphan `actual`s.
     * A concrete common object sidesteps that entirely and compiles on Android, iOS,
     * Web, Desktop AND every per-variant compilation. The flavor/build-type values are
     * resolved at codegen (constants); they are fixed for the built variant, so this is
     * equivalent to — and more robust than — the old platform-native runtime reads.
     */
    fun generate(spec: RuntimeApiSpec, hint: RuntimeVariantHint, outRoot: File): List<File> {
        outRoot.mkdirs()
        val pkgPath = spec.packageName.replace('.', '/')
        val dir = outRoot.resolve("commonMain").resolve(pkgPath)
        dir.mkdirs()
        val file = dir.resolve("KmpFlavorsRuntime.kt")
        file.writeText(RuntimeConcreteCommonTemplate.render(spec.packageName, hint))
        return listOf(file)
    }
}

internal object RuntimeConcreteCommonTemplate {
    /** Escape a value for embedding inside a Kotlin double-quoted string literal. */
    private fun esc(s: String): String = s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\${'$'}")

    fun render(pkg: String, hint: RuntimeVariantHint): String = """
// Generated by com.mobilebytelabs.kmp-product-flavors — DO NOT EDIT
package $pkg

/** Build-variant info resolved at codegen (fixed for the built variant). */
public object KmpFlavorsRuntime {
    public val flavorName: String = ${'"'}${esc(hint.flavorName)}${'"'}
    public val buildTypeName: String = ${'"'}${esc(hint.buildTypeName)}${'"'}
    public val bundleId: String = ${'"'}${esc(hint.bundleId)}${'"'}
    public val applicationId: String = bundleId
    public val appDisplayName: String = ${'"'}${esc(hint.appDisplayName)}${'"'}
    public val appVersion: String = ${'"'}${esc(hint.appVersion)}${'"'}
    public val isDebug: Boolean = ${hint.isDebug}
    public val isDemo: Boolean = ${hint.isDemo}
    public fun get(key: String): String? = when (key) {
        "flavorName" -> flavorName
        "buildTypeName" -> buildTypeName
        "bundleId" -> bundleId
        "applicationId" -> applicationId
        "appDisplayName" -> appDisplayName
        "appVersion" -> appVersion
        "isDebug" -> isDebug.toString()
        "isDemo" -> isDemo.toString()
        else -> null
    }
}
    """.trimIndent() + "\n"
}

